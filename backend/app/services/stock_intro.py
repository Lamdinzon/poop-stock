def _is_etf(ticker: str) -> bool:
    return ticker.startswith("00")


def build_intro(stock: StockPick) -> str:
    if _is_etf(stock.ticker):
        entity_line = f"{stock.name}（{stock.ticker}）是台灣上市的ETF（指數股票型基金）之一。"
        summary_part = ""
    else:
        entity_line = f"{stock.name}（{stock.ticker}）是台灣上市公司之一。"
        summary = COMPANY_SUMMARIES.get(stock.ticker)
        if summary:
            summary_part = f"主要業務是{summary}。"
        elif stock.industry:
            summary_part = f"屬於{stock.industry}產業。"
        else:
            summary_part = ""

    return (
        f"{entity_line}{summary_part}"
        "這只是幫你多認識一支股票的小知識，不是叫你現在就買。"
    )
